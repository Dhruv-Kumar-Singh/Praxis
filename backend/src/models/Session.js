/**
 * @collection sessions
 * Represents a single AI interview session from creation through completion.
 */

import mongoose from 'mongoose';

const { Schema, model } = mongoose;

// ── Sub-schemas ───────────────────────────────────────────────────────────────

const statusHistoryEntrySchema = new Schema(
  {
    status: { type: String, required: true },
    at: { type: Date, required: true, default: Date.now },
    note: { type: String, default: null },
  },
  { _id: false }
);

const failureSchema = new Schema(
  {
    stage: { type: String, required: true },   // e.g. 'evaluation', 'report-gen'
    reason: { type: String, required: true },
    attempts: { type: Number, default: 1 },
  },
  { _id: false }
);

// ── Root schema ───────────────────────────────────────────────────────────────

const sessionSchema = new Schema(
  {
    userId: {
      type: Schema.Types.Mixed,
      required: true,
    },
    candidateId: {
      type: Schema.Types.Mixed,
      default: null,
    },
    role: {
      type: String,
      default: 'Full-Stack Developer',
    },
    topic: {
      type: String,
      required: true,
      trim: true,
    },
    difficulty: {
      type: String,
      enum: ['easy', 'medium', 'hard'],
      default: 'medium',
      required: true,
    },
    expectedDurationMin: {
      type: Number,
      default: 30,
      min: 1,
    },
    status: {
      type: String,
      enum: [
        'draft',
        'created',
        'scheduled',
        'in_progress',
        'paused',
        'processing',
        'feedback_ready',
        'processing_failed',
        'completed',
        'failed',
        'cancelled',
        'abandoned',
      ],
      default: 'scheduled',
      required: true,
    },
    statusHistory: {
      type: [statusHistoryEntrySchema],
      default: [],
    },
    plan: {
      type: [Schema.Types.Mixed], // Question plan generated by PlanService
      default: [],
    },
    modelId: {
      type: String,
      default: 'gpt-6-luna',
    },
    promptVersion: {
      type: String,
      default: '1.0.0',
    },
    rubricVersion: {
      type: String,
      default: '1.0.0',
    },
    startedAt: {
      type: Date,
      default: null,
    },
    endedAt: {
      type: Date,
      default: null,
    },
    failure: {
      type: failureSchema,
      default: null,
    },
    version: {
      type: Number,
      default: 0, // Increment on every update for optimistic concurrency
    },
  },
  {
    collection: 'sessions',
    timestamps: true, // createdAt, updatedAt
  }
);

// ── Indexes ───────────────────────────────────────────────────────────────────

sessionSchema.index({ userId: 1, createdAt: -1 });
sessionSchema.index({ status: 1 });

const Session = model('Session', sessionSchema);
export default Session;
